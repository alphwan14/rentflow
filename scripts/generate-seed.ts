/**
 * Generates supabase/seed.sql from the demo dataset (src/demo/data.ts).
 *   npm run seed:generate
 *
 * Dates in the SQL are relative to the day the seed runs, so the demo always
 * shows the current month plus two months of history.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { matchPayment } from "../src/core/matching/engine";
import type { LeaseCandidate, MatchOutcome } from "../src/core/matching/types";
import { BUILDING_ID, DEMO, ORG_ID, PAST_TENANT, READY, RELATIVES, T, TENANTS, UNITS, VACANT, paymentsFor, uid, type DemoPayment } from "../src/demo/data";

const history: DemoPayment[] = [...paymentsFor(-2, 28), ...paymentsFor(-1, 28), ...paymentsFor(0, 31)];

// Two payments from last month that nobody has confirmed yet.
const inboxRaw: DemoPayment[] = [
  { code: "TKY8STRNG1", month: -1, day: 9, time: "10:22:05", amountCents: 12_000_00, phone: "254722987654", name: "MICHAEL OTIENO", ref: "", for: null },
  { code: "TKY8WRONG2", month: -1, day: 6, time: "18:40:51", amountCents: 15_000_00, phone: T.B11.phones[0], name: "ROSE WANJIRU KINYUA", ref: "B17", for: null },
];

const leases: LeaseCandidate[] = TENANTS.map((t) => ({
  leaseId: t.leaseId,
  tenantId: t.tenantId,
  tenantName: t.name,
  unitCode: t.unit,
  buildingId: BUILDING_ID,
  rentCents: t.rentCents,
  balanceCents: t.rentCents,
  oldestUnpaidDue: null,
  phones: t.phones,
}));
const rules = [{ kind: "phone" as const, pattern: RELATIVES.B3.phone, tenantId: T.B3.tenantId }];

function stored(o: MatchOutcome) {
  return {
    summary: o.summary,
    decision: o.decision,
    best: o.best ? { leaseIds: o.best.leaseIds, label: o.best.label, score: o.best.score, reasons: o.best.reasons.map((r) => ({ signal: r.signal, detail: r.detail })) } : null,
    candidates: o.candidates.map((c) => ({ leaseIds: c.leaseIds, label: c.label, score: c.score })),
  };
}

const data = {
  email: DEMO.email,
  org_id: ORG_ID,
  org_name: DEMO.orgName,
  building_id: BUILDING_ID,
  building_name: DEMO.buildingName,
  location: DEMO.location,
  paybill: DEMO.paybill,
  units: UNITS.map((u) => ({ id: u.unitId, code: u.code, rent: u.rentCents, deposit: u.depositCents, status: READY.has(u.code) ? "ready" : VACANT.has(u.code) ? "vacant" : "occupied" })),
  tenants: TENANTS.map((t) => ({ tenant_id: t.tenantId, lease_id: t.leaseId, unit_id: uid(`unit:${t.unit}`), name: t.name, phones: t.phones, rent: t.rentCents, arrears: t.arrearsCents })),
  history: history.map((p) => ({
    code: p.code,
    month: p.month,
    day: p.day,
    time: p.time,
    amount: p.amountCents,
    phone: p.phone,
    name: p.name,
    ref: p.ref,
    method: p.ref === "" ? "confirmed" : "auto",
    alloc: (p.for ?? []).map((u) => ({ lease_id: T[u].leaseId, amount_cents: p.amountCents })),
  })),
  rules: rules.map((r) => ({ kind: r.kind, pattern: r.pattern, tenant_id: r.tenantId })),
  past: { tenant_id: PAST_TENANT.tenantId, lease_id: PAST_TENANT.leaseId, unit_id: uid(`unit:${PAST_TENANT.unit}`), name: PAST_TENANT.name, phone: PAST_TENANT.phone, rent: PAST_TENANT.rentCents },
  inbox: inboxRaw.map((p) => {
    const o = matchPayment(
      { id: p.code, transCode: p.code, amountCents: p.amountCents, occurredAt: "2000-01-01T00:00:00+03:00", payerPhone: p.phone, payerName: p.name, accountRef: p.ref },
      { leases, rules },
    );
    return {
      code: p.code, month: p.month, day: p.day, time: p.time, amount: p.amountCents, phone: p.phone, name: p.name, ref: p.ref,
      status: o.decision === "unmatched" ? "unmatched" : "suggested",
      confidence: o.confidence,
      suggestion: stored(o),
      suggested: o.best?.leaseIds ?? null,
    };
  }),
};

const sql = `-- RentFlow demo seed. GENERATED by scripts/generate-seed.ts — do not edit by hand.
--
-- Demo login: ${DEMO.email} / ${DEMO.password}
-- One org on the Growth plan with a 40-unit building (A1–A20, B1–B20),
-- 36 tenants, two months of history plus this month so far, learned phone
-- numbers and a couple of payments waiting in "Who paid this?".
-- A sample statement for this month is at /statements/sample (demo org only).

-- ── Demo user (Supabase auth schema) ─────────────────────────────────────
do $user$
declare v_user uuid := '${uid("user")}';
begin
  if exists (select 1 from auth.users where email = '${DEMO.email}') then return; end if;
  if not exists (select 1 from information_schema.columns where table_schema = 'auth' and table_name = 'users' and column_name = 'encrypted_password') then
    raise notice 'Not a Supabase auth schema; create ${DEMO.email} yourself.';
    return;
  end if;
  execute $q$
    insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,
                            raw_app_meta_data, raw_user_meta_data, created_at, updated_at,
                            confirmation_token, email_change, email_change_token_new, recovery_token)
    values ('00000000-0000-0000-0000-000000000000', $1, 'authenticated', 'authenticated', $2,
            extensions.crypt($3, extensions.gen_salt('bf')), now(),
            '{"provider":"email","providers":["email"]}', jsonb_build_object('full_name', $4::text), now(), now(), '', '', '', '')
  $q$ using v_user, '${DEMO.email}', '${DEMO.password}', '${DEMO.ownerName}';
  execute $q$
    insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
    values (gen_random_uuid(), $1, $1::text, jsonb_build_object('sub', $1::text, 'email', $2::text, 'email_verified', true), 'email', now(), now(), now())
  $q$ using v_user, '${DEMO.email}';
end $user$;

-- ── Demo data ─────────────────────────────────────────────────────────────
-- @demo-data (supabase/tests run everything below this line against PGlite)
do $seed$
declare
  d jsonb := $json$${JSON.stringify(data)}$json$::jsonb;
  m0 date := date_trunc('month', public.nairobi_today())::date;
  v_today date := public.nairobi_today();
  v_track date := (date_trunc('month', public.nairobi_today()) - interval '2 months')::date;
  v_org uuid := (d ->> 'org_id')::uuid;
  v_building uuid := (d ->> 'building_id')::uuid;
  v_user uuid;
  r jsonb;
  v_event uuid;
  v_day date;
  v_uploads uuid[] := array[gen_random_uuid(), gen_random_uuid(), gen_random_uuid()];
begin
  select id into v_user from auth.users where email = d ->> 'email';
  if v_user is null then raise notice 'Demo user missing; skipping demo data.'; return; end if;
  if exists (select 1 from public.orgs where id = v_org) then raise notice 'Demo org already seeded.'; return; end if;
  perform set_config('request.jwt.claim.sub', v_user::text, true);

  insert into public.orgs (id, name, plan, created_by) values (v_org, d ->> 'org_name', 'growth', v_user);
  insert into public.members (org_id, user_id, role) values (v_org, v_user, 'owner');
  insert into public.buildings (id, org_id, name, location, default_due_day, tracking_from)
  values (v_building, v_org, d ->> 'building_name', d ->> 'location', 5, v_track);
  insert into public.payout_channels (org_id, building_id, kind, number) values (v_org, v_building, 'paybill', d ->> 'paybill');
  insert into public.units (id, org_id, building_id, code, rent_cents, deposit_cents, status)
  select (u ->> 'id')::uuid, v_org, v_building, u ->> 'code', (u ->> 'rent')::bigint, (u ->> 'deposit')::bigint, (u ->> 'status')::public.unit_status
    from jsonb_array_elements(d -> 'units') u;

  for r in select * from jsonb_array_elements(d -> 'tenants') loop
    insert into public.tenants (id, org_id, full_name) values ((r ->> 'tenant_id')::uuid, v_org, r ->> 'name');
    insert into public.tenant_phones (org_id, tenant_id, phone, is_primary)
    select v_org, (r ->> 'tenant_id')::uuid, p, n = 1 from jsonb_array_elements_text(r -> 'phones') with ordinality as x(p, n);
    insert into public.leases (id, org_id, unit_id, tenant_id, start_date, rent_cents, deposit_cents, due_day)
    values ((r ->> 'lease_id')::uuid, v_org, (r ->> 'unit_id')::uuid, (r ->> 'tenant_id')::uuid, v_track, (r ->> 'rent')::bigint, (r ->> 'rent')::bigint, 5);
    if (r ->> 'arrears')::bigint > 0 then
      perform public._post_charge((r ->> 'lease_id')::uuid, 'arrears_bf', null, v_track - 1, (r ->> 'arrears')::bigint, 'Balance brought forward', v_user);
    end if;
    perform public.generate_rent_charges((r ->> 'lease_id')::uuid, v_today);
  end loop;

  -- A past tenant: lived in A15 from the start of tracking, moved out at the end of last month owing rent.
  r := d -> 'past';
  insert into public.tenants (id, org_id, full_name) values ((r ->> 'tenant_id')::uuid, v_org, r ->> 'name');
  insert into public.tenant_phones (org_id, tenant_id, phone, is_primary) values (v_org, (r ->> 'tenant_id')::uuid, r ->> 'phone', true);
  insert into public.leases (id, org_id, unit_id, tenant_id, start_date, end_date, rent_cents, deposit_cents, due_day, status, ended_at)
  values ((r ->> 'lease_id')::uuid, v_org, (r ->> 'unit_id')::uuid, (r ->> 'tenant_id')::uuid, v_track, m0 - 1, (r ->> 'rent')::bigint, 0, 5, 'ended', now());
  perform public.generate_rent_charges((r ->> 'lease_id')::uuid, v_today);

  for i in 1..3 loop
    insert into public.statement_uploads (id, org_id, building_id, filename, format, period_start, period_end, uploaded_by, created_at)
    values (v_uploads[i], v_org, v_building, 'mpesa-statement-' || to_char((m0 + make_interval(months => i - 3)), 'YYYY-MM') || '.csv',
            'M-Pesa business statement', (m0 + make_interval(months => i - 3))::date,
            least(v_today, ((m0 + make_interval(months => i - 2))::date - 1)), v_user,
            least(now(), (m0 + make_interval(months => i - 2))::timestamptz + interval '2 days'));
  end loop;

  for r in select * from jsonb_array_elements(d -> 'history') loop
    v_day := (m0 + make_interval(months => (r ->> 'month')::int))::date + ((r ->> 'day')::int - 1);
    continue when v_day > v_today;
    insert into public.payment_events (org_id, source, trans_code, amount_cents, occurred_at, payer_phone, payer_name, account_ref, building_id, upload_id, raw)
    values (v_org, 'mpesa_statement', r ->> 'code', (r ->> 'amount')::bigint, (v_day::text || ' ' || (r ->> 'time') || '+03')::timestamptz,
            r ->> 'phone', r ->> 'name', nullif(r ->> 'ref', ''), v_building, v_uploads[(r ->> 'month')::int + 3], '{"seed": true}')
    returning id into v_event;
    perform public._post_payment(v_event, r -> 'alloc', r ->> 'method', case when r ->> 'method' = 'auto' then 0.97 end, v_user);
  end loop;

  insert into public.match_rules (org_id, kind, pattern, tenant_id, hits, created_by)
  select v_org, (x ->> 'kind')::public.rule_kind, x ->> 'pattern', (x ->> 'tenant_id')::uuid, 2, v_user from jsonb_array_elements(d -> 'rules') x;

  for r in select * from jsonb_array_elements(d -> 'inbox') loop
    v_day := (m0 + make_interval(months => (r ->> 'month')::int))::date + ((r ->> 'day')::int - 1);
    insert into public.payment_events (org_id, source, trans_code, amount_cents, occurred_at, payer_phone, payer_name, account_ref,
                                       building_id, upload_id, raw, status, confidence, suggestion, suggested_lease_ids, processed_at)
    values (v_org, 'mpesa_statement', r ->> 'code', (r ->> 'amount')::bigint, (v_day::text || ' ' || (r ->> 'time') || '+03')::timestamptz,
            r ->> 'phone', r ->> 'name', nullif(r ->> 'ref', ''), v_building, v_uploads[2], '{"seed": true}',
            (r ->> 'status')::public.event_status, (r ->> 'confidence')::numeric, r -> 'suggestion',
            (select array_agg(x::uuid) from jsonb_array_elements_text(r -> 'suggested') x), now());
  end loop;

  update public.statement_uploads su
     set total_payments = s.total, new_events = s.total, auto_matched = s.matched, suggested = s.open
    from (select upload_id, count(*) as total, count(*) filter (where status = 'matched') as matched,
                 count(*) filter (where status in ('suggested', 'unmatched')) as open
            from public.payment_events where org_id = v_org group by upload_id) s
   where su.id = s.upload_id;
  delete from public.statement_uploads where org_id = v_org and total_payments = 0;
end $seed$;
`;

writeFileSync(join(__dirname, "..", "supabase", "seed.sql"), sql);
console.log(`supabase/seed.sql written: ${TENANTS.length} tenants, ${history.length} payments, ${data.inbox.length} inbox items`);
